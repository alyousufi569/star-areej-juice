-- STAR AREEJ JUICE: schema + Row Level Security
-- Run this entire script in Supabase > SQL Editor > New query.
-- This adds the new site tables/columns and replaces policies on these tables.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  category text not null,
  description text,
  image_url text,
  prices jsonb not null default '{"small":5,"medium":8,"large":10}'::jsonb,
  calories jsonb not null default '{}'::jsonb,
  active boolean not null default true,
  sort_order integer not null default 0,
  updated_at timestamptz not null default now()
);
alter table public.products add column if not exists calories jsonb not null default '{}'::jsonb;
alter table public.products add column if not exists sort_order integer not null default 0;
alter table public.products add column if not exists active boolean not null default true;
alter table public.products add column if not exists updated_at timestamptz not null default now();
alter table public.products add column if not exists image_url text;
alter table public.products add column if not exists description text;
alter table public.products add column if not exists prices jsonb not null default '{"small":5,"medium":8,"large":10}'::jsonb;

create table if not exists public.store_offers (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  title text not null,
  description text,
  price numeric(10,2),
  original_price numeric(10,2),
  image_url text,
  active boolean not null default true,
  starts_at timestamptz,
  ends_at timestamptz,
  sort_order integer not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  customer_name text not null,
  phone text not null,
  order_type text,
  address text,
  items jsonb not null default '[]'::jsonb,
  total numeric(10,2) not null default 0,
  status text not null default 'جديد',
  notes text
);
alter table public.orders add column if not exists customer_name text;
alter table public.orders add column if not exists phone text;
alter table public.orders add column if not exists order_type text;
alter table public.orders add column if not exists address text;
alter table public.orders add column if not exists items jsonb not null default '[]'::jsonb;
alter table public.orders add column if not exists total numeric(10,2) not null default 0;
alter table public.orders add column if not exists status text not null default 'جديد';
alter table public.orders add column if not exists notes text;
alter table public.orders add column if not exists created_at timestamptz not null default now();
alter table public.orders add column if not exists table_number text;
alter table public.orders add column if not exists payment_method text not null default 'كاش';

-- Admin registry must already contain your Supabase Auth user_id.
create table if not exists public.store_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;
alter table public.store_offers enable row level security;
alter table public.orders enable row level security;
alter table public.store_admins enable row level security;

-- Rebuild policies on these tables to avoid old permissive policies overriding the new rules.
do $$
declare pol record;
begin
  for pol in
    select schemaname, tablename, policyname
    from pg_policies
    where schemaname='public'
      and tablename in ('products','store_offers','orders','store_admins')
  loop
    execute format('drop policy if exists %I on %I.%I', pol.policyname, pol.schemaname, pol.tablename);
  end loop;
end $$;

create policy "admins can read their own registry row"
on public.store_admins for select to authenticated
using (user_id = (select auth.uid()));

create policy "public can read active products"
on public.products for select to anon
using (active = true);

create policy "authenticated can read active products"
on public.products for select to authenticated
using (active = true);

create policy "admins manage products"
on public.products for all to authenticated
using (exists (select 1 from public.store_admins a where a.user_id = (select auth.uid())))
with check (exists (select 1 from public.store_admins a where a.user_id = (select auth.uid())));

create policy "public can read active offers"
on public.store_offers for select to anon
using (active = true);

create policy "authenticated can read active offers"
on public.store_offers for select to authenticated
using (active = true);

create policy "admins manage offers"
on public.store_offers for all to authenticated
using (exists (select 1 from public.store_admins a where a.user_id = (select auth.uid())))
with check (exists (select 1 from public.store_admins a where a.user_id = (select auth.uid())));

create policy "customers can submit orders"
on public.orders for insert to anon, authenticated
with check (
  customer_name is not null and length(trim(customer_name)) > 0
  and phone is not null and length(trim(phone)) > 0
  and jsonb_typeof(items) = 'array'
  and total >= 0
);

create policy "admins can view orders"
on public.orders for select to authenticated
using (exists (select 1 from public.store_admins a where a.user_id = (select auth.uid())));

create policy "admins can update orders"
on public.orders for update to authenticated
using (exists (select 1 from public.store_admins a where a.user_id = (select auth.uid())))
with check (exists (select 1 from public.store_admins a where a.user_id = (select auth.uid())));

create policy "admins can delete orders"
on public.orders for delete to authenticated
using (exists (select 1 from public.store_admins a where a.user_id = (select auth.uid())));

grant select on public.products, public.store_offers to anon, authenticated;
grant insert, update, delete on public.products, public.store_offers to authenticated;
grant insert on public.orders to anon, authenticated;
grant select, update, delete on public.orders to authenticated;
grant select on public.store_admins to authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- Public product images; only signed-in store admins may upload/change/delete.
insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do update set public = true;

drop policy if exists "Public can view product images" on storage.objects;
drop policy if exists "Admins can upload product images" on storage.objects;
drop policy if exists "Admins can update product images" on storage.objects;
drop policy if exists "Admins can delete product images" on storage.objects;

create policy "Public can view product images"
on storage.objects for select to anon, authenticated
using (bucket_id = 'product-images');

create policy "Admins can upload product images"
on storage.objects for insert to authenticated
with check (
  bucket_id = 'product-images'
  and exists (select 1 from public.store_admins a where a.user_id = (select auth.uid()))
);

create policy "Admins can update product images"
on storage.objects for update to authenticated
using (
  bucket_id = 'product-images'
  and exists (select 1 from public.store_admins a where a.user_id = (select auth.uid()))
)
with check (
  bucket_id = 'product-images'
  and exists (select 1 from public.store_admins a where a.user_id = (select auth.uid()))
);

create policy "Admins can delete product images"
on storage.objects for delete to authenticated
using (
  bucket_id = 'product-images'
  and exists (select 1 from public.store_admins a where a.user_id = (select auth.uid()))
);

-- Enable realtime for live catalog and offer refresh.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname='public' and tablename='products'
  ) then
    alter publication supabase_realtime add table public.products;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname='public' and tablename='store_offers'
  ) then
    alter publication supabase_realtime add table public.store_offers;
  end if;
end $$;
